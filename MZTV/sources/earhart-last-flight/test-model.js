const assert=require('node:assert/strict');
require('./model.js');
const M=globalThis.MZLastFlight;
const a=M.simulate(19370702,M.DEFAULTS),b=M.simulate(19370702,M.DEFAULTS);
assert.deepEqual(a,b,'same seed must reproduce the same flight');
assert(a.points.length>40,'flight integration should produce samples');
assert(a.points.every(p=>Number.isFinite(p.lat)&&Number.isFinite(p.lon)&&p.fuel>=0));
assert(a.points.every((p,i)=>!i||p.t>a.points[i-1].t));
assert(a.points.every((p,i)=>!i||p.fuel<=a.points[i-1].fuel));
assert(a.fuel0<=1151);
assert(M.distKm(M.LAE,M.HOWLAND)>3900&&M.distKm(M.LAE,M.HOWLAND)<4300);
const zero=M.simulate(42,{...M.DEFAULTS,wind:-25});
const pos=M.simulate(42,{...M.DEFAULTS,wind:25});
assert(pos.end.lat>zero.end.lat,'more northward wind should move north');
const low=M.simulate(42,{...M.DEFAULTS,fuelStart:850});
const high=M.simulate(42,{...M.DEFAULTS,fuelStart:1130});
assert(high.end.t>low.end.t,'higher tank load should increase endurance for same seed');
assert(M.ensemble(7,12).length===12);
assert(M.stats(M.ensemble(7,12)).trials===12);
assert(Math.abs(M.interpolate(a,0).lat-M.LAE.lat)<1e-9);
assert(Math.abs(M.interpolate(a,999).t-a.end.t)<1e-9);
console.log('PASS / 12 software sanity checks. Not historical or aerodynamic validation.');